/**
 * THE ONE AUTOMATIC PROOF THAT THESE SCREENS READ POSTGRESQL.
 *
 * Everything else in this package renders a component over a fixture. A fixture cannot prove a
 * read — it proves what the renderer does with a row somebody typed. The precedent this repository
 * already paid for is in `services/stream_gateway/stream_gateway/tickets.py`: `TicketRegistry`
 * keeps its records in a `dict`, its own docstring calls that an F0 shortcut, every one of its
 * tests passes, and the data is gone after a restart.
 *
 * So this file drives the WHOLE CHAIN, and nothing in it is a stand-in:
 *
 *   psql INSERT  →  PostgreSQL  →  control plane (uvicorn, real HTTP)  →  Next.js server  →  HTML
 *
 * The rows are inserted by `tools/e2e_db_render.sh` with raw SQL through NO CODE OF THIS PACKAGE
 * and none of the control plane's either — the same discipline as
 * `services/control_plane/tests/test_jobs_api.py`. If the dashboard ever starts serving something
 * it made up, an identifier generated by the shell script will stop appearing in the markup.
 *
 * A MISSING ENVIRONMENT IS A FAILURE, NEVER A SKIP. `beforeAll` throws when a variable is absent,
 * which marks every test in the file as failed. This is the rule `services/control_plane/tests/
 * conftest.py` states for the `pool` fixture: "pytest.mark.skipif(not DSN, ...)` is the shape this
 * repository has to stop using" — a module that reports "2 tests collected, 2 skipped" exits 0 and
 * reads as green. `tools/verify_run.mjs` independently refuses a run with any skipped test.
 */
import { beforeAll, describe, expect, it } from "vitest";

/** Everything the harness must hand over. Missing any of it is a failure, not a skip. */
const REQUIRED = [
  "WENEXT_E2E_BASE_URL",
  "WENEXT_E2E_OPERATOR_PASSWORD",
  "WENEXT_E2E_JOB_ID",
  "WENEXT_E2E_FRESH_JOB_ID",
  "WENEXT_E2E_LEASE_OWNER",
  "WENEXT_E2E_AUDIT_KIND",
] as const;

type Required = (typeof REQUIRED)[number];

const environment: Record<string, string> = {};

/** Routes behind the auth boundary. `/login`, `/login/submit`, `/logout` and `/healthz` are not. */
const GATED_PATHS: readonly string[] = ["/", "/jobs", "/audit", "/transitions", "/approvals"];

function required(name: Required): string {
  const value = environment[name];
  if (value === undefined) {
    throw new Error(`brak ${name} — harness nie przekazał danych zaszczepionych do bazy`);
  }
  return value;
}

function url(pathname: string): string {
  return `${required("WENEXT_E2E_BASE_URL").replace(/\/+$/, "")}${pathname}`;
}

interface Fetched {
  readonly status: number;
  readonly location: string | null;
  readonly body: string;
  readonly setCookie: readonly string[];
}

async function get(pathname: string, cookie?: string): Promise<Fetched> {
  const response = await fetch(url(pathname), {
    headers: cookie === undefined ? {} : { cookie },
    redirect: "manual",
  });
  return {
    status: response.status,
    location: response.headers.get("location"),
    body: await response.text(),
    setCookie: response.headers.getSetCookie(),
  };
}

/** Log in the way a browser would: a form POST to the dashboard, never to the control plane. */
async function logIn(password: string): Promise<Fetched> {
  const response = await fetch(url("/login/submit"), {
    method: "POST",
    headers: { "content-type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({ password }).toString(),
    redirect: "manual",
  });
  return {
    status: response.status,
    location: response.headers.get("location"),
    body: await response.text(),
    setCookie: response.headers.getSetCookie(),
  };
}

function handleCookieFrom(response: Fetched): string {
  const header = response.setCookie.find((value) => value.startsWith("wenext_dashboard_handle="));
  if (header === undefined) {
    throw new Error(
      `logowanie nie odesłało ciasteczka uchwytu; nagłówki: ${JSON.stringify(response.setCookie)}`,
    );
  }
  return header.split(";")[0] ?? "";
}

let cookie = "";

beforeAll(async () => {
  const missing: string[] = [];
  for (const name of REQUIRED) {
    const value = process.env[name];
    if (value === undefined || value === "") {
      missing.push(name);
      continue;
    }
    environment[name] = value;
  }
  if (missing.length > 0) {
    throw new Error(
      `BRAK ŚRODOWISKA E2E: ${missing.join(", ")}. To jest PORAŻKA, nie pominięcie — test ` +
        "pominięty po cichu przechodzi w podsumowaniu za zielony. Uruchom: " +
        "REPO_ROOT=$PWD bash apps/dashboard/tools/e2e_db_render.sh",
    );
  }

  const login = await logIn(required("WENEXT_E2E_OPERATOR_PASSWORD"));
  expect(login.status, `logowanie zwróciło ${login.status}, ciało ${login.body.slice(0, 200)}`).toBe(303);
  cookie = handleCookieFrom(login);
});

describe("the dashboard against real PostgreSQL", () => {
  it("renders_the_job_id_inserted_straight_into_postgres", async () => {
    // THE test. The identifier was written by `psql`, through no code of this package and none of
    // the control plane's. Finding it in the markup is the only automatic evidence that this screen
    // reads the canonical store rather than something it assembled itself.
    const jobId = required("WENEXT_E2E_JOB_ID");
    const page = await get("/jobs", cookie);

    expect(page.status).toBe(200);
    // Count-like assertions first: an error page would satisfy "does not say brak danych".
    expect(page.body.length).toBeGreaterThan(500);
    expect(page.body).toContain("<table");
    // The MARKER, not the phrase. The shell says on every screen that "pusty ekran znaczy „brak
    // danych”", so a substring test on the words matches the layout's own explanation — measured on
    // the first end-to-end run, where it failed against a page full of real rows. `data-state` is
    // rendered only by `EmptyState`, which is exactly the thing that must not be there.
    expect(page.body).not.toContain('data-state="brak odpowiedzi"');
    expect(page.body).not.toContain('data-state="brak danych"');

    expect(page.body, `w HTML-u nie ma joba ${jobId}`).toContain(jobId);
    // And the row's lease columns, which come from a SECOND read per row (`app/jobs/page.tsx`):
    // seeing the owner proves that read happened too, and that it was not silently swallowed.
    expect(page.body).toContain(required("WENEXT_E2E_LEASE_OWNER"));
    expect(page.body).not.toContain("nie odczytano");
  });

  it("renders_the_attempt_history_and_the_retry_verdict_from_postgres", async () => {
    // The seeded job's latest attempt has `failure_class = 'SUBMIT_STARTED'`, so the control plane
    // computes `may_retry_automatically = false` (contracts) and the screen must print ZABRONIONE.
    // A dashboard recomputing the rule locally, or defaulting it, changes this byte.
    const page = await get(`/jobs/${required("WENEXT_E2E_JOB_ID")}`, cookie);

    expect(page.status).toBe(200);
    expect(page.body).toContain("SUBMIT_STARTED");
    expect(page.body).toContain('data-retry-verdict="ZABRONIONE"');
    expect(page.body).not.toContain('data-retry-verdict="DOZWOLONE"');
    // The lease generations, which only `job_attempts` can supply.
    expect(page.body).toContain("generacje lease");
    expect(page.body).toContain(required("WENEXT_E2E_LEASE_OWNER"));
  });

  it("no_retry_affordance_on_the_real_job_detail_page", async () => {
    // The unit suite proves this over all eight states for the VIEW. Here it is the whole page, as
    // served: shell, navigation and all. The only form on a rendered screen is the logout, and no
    // form action or link may point at anything that could retry a job.
    const page = await get(`/jobs/${required("WENEXT_E2E_JOB_ID")}`, cookie);
    expect(page.status).toBe(200);

    const forms = Array.from(page.body.matchAll(/<form[^>]*action="([^"]*)"/g)).map(
      (match) => match[1],
    );
    expect(forms).toEqual(["/logout"]);

    const links = Array.from(page.body.matchAll(/<a[^>]*href="([^"]*)"/g)).map((match) => match[1] ?? "");
    expect(links.length).toBeGreaterThan(0);
    for (const href of links) {
      expect(href, `link ${href} wygląda na akcję, a nie na nawigację`).not.toMatch(
        /retry|ponow|ponów|redispatch|wymus|wymuś/i,
      );
    }
    // No inline handler anywhere: there is no client JavaScript in this package at all.
    expect(page.body).not.toMatch(/\son(click|submit|change)=/i);
  });

  it("the_audit_view_shows_the_event_inserted_into_postgres", async () => {
    const kind = required("WENEXT_E2E_AUDIT_KIND");
    const page = await get("/audit", cookie);

    expect(page.status).toBe(200);
    expect(page.body).toContain("<table");
    expect(page.body).toContain(kind);
    // The tally under the table is the second channel: a view filtering a kind would have to drop
    // it from both, and both are checked.
    expect(page.body).toContain("Rodzaje na tej stronie (bez filtra)");
    expect(page.body).not.toContain('data-state="brak danych"');
  });

  it("an_unknown_job_id_says_there_is_no_such_job", async () => {
    // A 404 from the control plane is a MEASURED fact and gets its own screen. It must not be
    // rendered as an empty attempt list ("brak danych") nor as a failed read ("brak odpowiedzi").
    const page = await get("/jobs/00000000-0000-4000-8000-000000000000", cookie);

    expect(page.status).toBe(200);
    expect(page.body).toContain('data-state="nie ma takiego joba"');
    expect(page.body).not.toContain('data-state="brak danych"');
    expect(page.body).not.toContain('data-state="brak odpowiedzi"');
  });

  it("a_job_with_no_attempts_renders_the_measured_empty_and_no_retry_permission", async () => {
    // The other end of the same rule: a job that exists and has never been claimed. The attempts
    // list is a MEASURED empty, and "no attempts" is not "retry allowed".
    const page = await get(`/jobs/${required("WENEXT_E2E_FRESH_JOB_ID")}`, cookie);

    expect(page.status).toBe(200);
    expect(page.body).toContain('data-state="brak danych"');
    expect(page.body).toContain('data-retry-verdict="BRAK PRÓB"');
    expect(page.body).not.toContain('data-retry-verdict="DOZWOLONE"');
  });

  it("no_view_renders_data_without_a_session", async () => {
    // Every gated route, asked WITHOUT the cookie. Each must redirect to the login screen and leak
    // nothing: no job identifier, no operator identifier, no token, no handle.
    expect(GATED_PATHS.length).toBe(5);
    const jobId = required("WENEXT_E2E_JOB_ID");
    const secrets = [jobId, required("WENEXT_E2E_LEASE_OWNER"), cookie.split("=")[1] ?? "x"];
    expect(secrets.every((secret) => secret.length > 8)).toBe(true);

    const paths = [...GATED_PATHS, `/jobs/${jobId}`];
    const UUID = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i;

    for (const pathname of paths) {
      const page = await get(pathname);

      expect([302, 303, 307, 308], `${pathname} zwróciło ${page.status}`).toContain(page.status);
      expect(page.location ?? "", pathname).toContain("/login");

      // MEASURED, AND WORTH WRITING DOWN: Next.js answers a redirected DOCUMENT request with a 307
      // whose body still carries the shell plus a flight payload, and that payload echoes the
      // REQUESTED PATH SEGMENTS — so `/jobs/<id>` comes back containing `<id>`. That is the
      // caller's own input handed back, not a disclosure: an unauthenticated caller who typed an
      // identifier already had it. The assertion is therefore scoped to identifiers the caller did
      // NOT supply, and the count is checked so the filter cannot quietly empty the list.
      const notSupplied = secrets.filter((secret) => !pathname.includes(secret));
      expect(notSupplied.length, pathname).toBeGreaterThanOrEqual(2);
      for (const secret of notSupplied) {
        expect(page.body, `${pathname} wypuścił ${secret.slice(0, 8)}…`).not.toContain(secret);
      }

      // AND NO RENDERED DATA OF ANY KIND. This replaces an earlier bound on the body's LENGTH,
      // which was both wrong (6289 bytes measured) and beside the point: what matters is that no
      // screen was rendered, not how many bytes the framework sent.
      expect(page.body, `${pathname} zawiera 64-znakowy hash`).not.toMatch(/\b[0-9a-f]{64}\b/i);
      expect(page.body, pathname).not.toContain("<table");
      expect(page.body, pathname).not.toContain("data-state=");
      expect(page.body, pathname).not.toContain("data-retry-verdict");
      // For every path that does not itself name an identifier, NO UUID may appear at all.
      if (!UUID.test(pathname)) {
        expect(page.body, `${pathname} zawiera UUID`).not.toMatch(UUID);
      }
    }
  });

  it("the_control_plane_session_token_never_appears_in_a_dashboard_response", async () => {
    // D-016, measured on the wire. The browser is given a handle; the control plane's token stays
    // in the Next.js process. Two things are checked: the login response sets ONLY the handle
    // cookie, and no rendered page contains the handle's value or a control plane cookie name.
    const login = await logIn(required("WENEXT_E2E_OPERATOR_PASSWORD"));
    expect(login.status).toBe(303);

    const names = login.setCookie.map((header) => header.split("=")[0]);
    expect(names).toEqual(["wenext_dashboard_handle"]);
    expect(names).not.toContain("wenext_operator_session");
    for (const header of login.setCookie) {
      expect(header).toContain("HttpOnly");
      expect(header).toContain("SameSite=Strict");
    }

    const freshCookie = handleCookieFrom(login);
    const handleValue = freshCookie.split("=")[1] ?? "";
    expect(handleValue.length).toBeGreaterThan(16);

    for (const pathname of ["/jobs", "/audit", `/jobs/${required("WENEXT_E2E_JOB_ID")}`]) {
      const page = await get(pathname, freshCookie);
      expect(page.status, pathname).toBe(200);
      expect(page.body, pathname).not.toContain("wenext_operator_session");
      // Not even the handle: a page echoing its own session cookie hands it to anything that can
      // read the document.
      expect(page.body, pathname).not.toContain(handleValue);
    }
  });

  it("logging_out_ends_the_session_on_both_sides", async () => {
    // A logout that only clears the cookie leaves the control plane session valid for anybody
    // holding a copy of the token. After this, the SAME cookie must no longer render a screen.
    const login = await logIn(required("WENEXT_E2E_OPERATOR_PASSWORD"));
    const ownCookie = handleCookieFrom(login);
    expect((await get("/jobs", ownCookie)).status).toBe(200);

    const response = await fetch(url("/logout"), {
      method: "POST",
      headers: { cookie: ownCookie },
      redirect: "manual",
    });
    expect(response.status).toBe(303);
    expect(response.headers.get("location")).toContain("/login");
    expect(response.headers.getSetCookie().join(";")).toContain("Max-Age=0");

    const after = await get("/jobs", ownCookie);
    expect([302, 303, 307, 308]).toContain(after.status);
    expect(after.location ?? "").toContain("/login");
  });

  it("a_wrong_password_is_refused_without_saying_why", async () => {
    // The refusal must not distinguish a wrong password from an unprovisioned operator — the
    // control plane deliberately does not (`auth.verify_credential`), and neither may this screen.
    const refused = await logIn("to-nie-jest-hasło-operatora");
    expect(refused.status).toBe(303);
    expect(refused.location ?? "").toContain("blad=odmowa");
    expect(refused.setCookie).toEqual([]);

    const screen = await get("/login?blad=odmowa");
    expect(screen.status).toBe(200);
    expect(screen.body).toContain('data-login-error="odmowa"');
    // Only the refusal marker, never the "the read did not happen" one: the two are different
    // statements and mixing them would make an outage look like a typo.
    expect(screen.body).not.toContain('data-login-error="niedostepne"');
    // And the screen says outright that it is NOT telling the operator which case this is. The
    // assertion is on that sentence rather than on the absence of a phrase — an earlier version
    // asserted `not.toContain("hasło jest złe")` and failed against the very sentence that
    // promises not to distinguish the cases, which is a test measuring its own wording.
    expect(screen.body).toContain("nie mówi, czy hasło jest złe, czy operator nie jest w ogóle");
  });

  it("the_health_route_answers_without_a_session_and_says_nothing_about_the_api", async () => {
    // `docker-compose.yml` waits on this, so it must be outside the boundary. And it must NOT
    // report on the control plane: a dashboard answering 200 here while the API is unreachable
    // would be claiming more than it measured.
    const page = await get("/healthz");
    expect(page.status).toBe(200);
    expect(page.body).toContain("proces odpowiada");
    expect(page.body).not.toContain("control plane: OK");
  });
});
