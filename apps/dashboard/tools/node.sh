#!/usr/bin/env bash
# Runs one npm/node command inside the PINNED Node image from versions.lock.toml.
#
# WHY THIS SCRIPT EXISTS (see apps/dashboard/NOTES.md for the full reasoning):
# the host has Node v24.12.0 while `versions.lock.toml [stack.js]` pins 24.20.0 and
# `node:24.20.0-trixie-slim`. The image that ships (apps/dashboard/Dockerfile) runs the
# pinned version, so a build or a test executed on the host's PATH would prove something
# about a runtime nobody deploys. This repository already answers that question once, for
# ruff, in the Makefile: "formatowanie ma dawać ten sam wynik u każdego i w CI.
# Cena: jedno docker run." Same trade, same price.
#
# NOTHING HERE FALLS BACK TO THE HOST. If the pin cannot be read, or docker is absent, the
# script fails. A toolchain that silently degrades to whatever is on PATH is the same
# disease as a gate announcing GO without a measurement (D-007), one layer down.
#
# TWO OPT-IN KNOBS, BOTH OFF BY DEFAULT, both for the end-to-end run:
#
#   WENEXT_NODE_HOST_GATEWAY=1
#       adds `--add-host=host.docker.internal:host-gateway`, which lets the container reach a
#       service listening on the HOST's 127.0.0.1. Measured on this host 2026-08-31: a container
#       reaches `http://host.docker.internal:<port>` when the host process is bound to loopback
#       only, so the control plane does NOT have to be exposed on 0.0.0.0 for the e2e run. Off by
#       default because the unit suite must stay hermetic — it talks to nothing.
#
#   WENEXT_NODE_ENV_PASSTHROUGH="A B C"
#       forwards those environment variables into the container. Named explicitly rather than
#       `--env-file` or a blanket copy of the environment: a runner that passes everything
#       eventually passes a credential nobody meant to send.
#
#   WENEXT_NODE_PUBLISH="127.0.0.1:3100:3100"
#       publishes a port on the HOST. Off by default and loopback by habit rather than by luck:
#       the render review drives the built application with a browser running on the host, and a
#       container whose port nobody published cannot be reached from one. Every other use of this
#       script needs no port, which is why this is a knob and not a default — a published port
#       that nobody asked for is a service on the network that nobody decided to run.
#
# Usage:  tools/node.sh npm ci
#         tools/node.sh npm run build
#         tools/node.sh sh -c 'npm run build && npm test'
set -euo pipefail

if [ "$#" -eq 0 ]; then
  echo "BŁĄD: tools/node.sh wymaga polecenia do uruchomienia (np. 'npm ci')" >&2
  exit 2
fi

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_DIR="$(cd "$HERE/.." && pwd)"
ROOT="$(cd "$APP_DIR/../.." && pwd)"
LOCK="$ROOT/versions.lock.toml"

if [ ! -f "$LOCK" ]; then
  echo "BŁĄD: nie ma $LOCK — nie ma z czego odczytać przypiętej wersji Node'a" >&2
  exit 2
fi

# Read `[stack.js]` with grep rather than a TOML parser: this script must run before any
# dependency is installed, and the host interpreter is not ours to assume. Both values are
# REQUIRED — an empty result exits instead of producing `node:` or a floating tag.
read_pin() {
  local key="$1" value
  value="$(grep -E "^[[:space:]]*${key}[[:space:]]*=" "$LOCK" | head -1 | sed -E 's/.*=[[:space:]]*"([^"]*)".*/\1/')"
  if [ -z "$value" ]; then
    echo "BŁĄD: versions.lock.toml nie podaje '${key}' — piny Node'a są jedynym źródłem prawdy" >&2
    exit 2
  fi
  printf '%s' "$value"
}

NODE_IMAGE="$(read_pin node_image)"
NODE_IMAGE_DIGEST="$(read_pin node_image_digest)"
IMAGE="${NODE_IMAGE}@${NODE_IMAGE_DIGEST}"

if ! command -v docker >/dev/null 2>&1; then
  echo "BŁĄD ŚRODOWISKA: brak dockera, a łańcuch narzędzi JS jedzie WYŁĄCZNIE z obrazu $IMAGE." >&2
  echo "                 Node z PATH-u hosta nie jest ścieżką zapasową — patrz apps/dashboard/NOTES.md." >&2
  exit 2
fi

# D-008: the credential helper on this development host hangs, so every docker call in this
# repository goes through the config generated by `make env`. Pointed at only when it exists,
# so the script still works on a host that never needed the workaround.
if [ -d "$ROOT/infra/docker-config" ]; then
  export DOCKER_CONFIG="$ROOT/infra/docker-config"
fi

# The npm cache lives OUTSIDE the repository, and that is not tidiness.
#
# Measured: the cache reaches ~390 MB. Every service image in this repo builds with
# `context: .` and the root `.dockerignore` does not exclude Node artefacts, so a cache in the
# working tree would be shipped as build context to every unrelated image in the stack. A docker
# named volume was the other candidate and was rejected: it is created root-owned, while this
# container runs as the invoking user precisely so that `node_modules` and `.next` do not come
# back owned by root on the host.
CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/wenext/dashboard-npm"
mkdir -p "$CACHE_DIR"

DOCKER_ARGS=(
  --rm
  --user "$(id -u):$(id -g)"
  -v "$ROOT:/repo"
  -v "$CACHE_DIR:/npm-cache"
  -w /repo/apps/dashboard
  -e HOME=/tmp
  -e NPM_CONFIG_CACHE=/npm-cache
  -e NEXT_TELEMETRY_DISABLED=1
  -e CI=1
)

if [ "${WENEXT_NODE_HOST_GATEWAY:-0}" = "1" ]; then
  DOCKER_ARGS+=(--add-host=host.docker.internal:host-gateway)
fi

if [ -n "${WENEXT_NODE_PUBLISH:-}" ]; then
  DOCKER_ARGS+=(-p "$WENEXT_NODE_PUBLISH")
fi

# Named variables only. A missing one is FORWARDED AS MISSING rather than as an empty string:
# the e2e suite refuses to run without its variables, and an empty value would look like a
# configuration somebody chose.
for name in ${WENEXT_NODE_ENV_PASSTHROUGH:-}; do
  if [ -n "${!name-}" ]; then
    DOCKER_ARGS+=(-e "$name=${!name}")
  fi
done

exec docker run "${DOCKER_ARGS[@]}" "$IMAGE" "$@"
