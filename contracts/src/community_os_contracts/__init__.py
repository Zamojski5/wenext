"""Domain contracts of Community Marketing Autopilot OS — phases E1.F0 and E1.F1.

This package is the single source of truth for the types, enums and invariants extracted
from ROADMAP_CODEX_CDP_COMMUNITY_OS.md. The remaining deliverables import from here and do
NOT create their own copies of these definitions.

Principle: if the document says that something is forbidden, it has to be made impossible
here by a type or a validator — not by a comment.

E1.F1 adds four things that more than one later package needs, so they are built once, here:
`jobs.JobTransportPort` with its fencing token (L5202, L5208), the six transition tables of
sections 14.8 and 16.1 (`transitions`), `ActionProposalRevision.supersede` and the
`SideEffectAuthorization` proof returned by `authorize_and_consume` (L5217-5218).

`__all__` below is checked by `tests/test_repo_consistency.py::test_every_all_entry_is_actually_bound`.
That test exists because two packages in this repository listed 27 names that had never been
bound, and `from <package> import *` had been failing for months without anyone noticing.
"""

